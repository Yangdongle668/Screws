// Article Studio text format. The model writes plain text with @@ markers instead of JSON, so quotes,
// brackets or line breaks inside the prose can never invalidate the whole article.
//
// @@TITLE / @@META_TITLE / @@META_DESCRIPTION / @@INTRO / @@SECTION <heading> (repeatable)
// @@EXAMPLE (optional) / @@CHECKLIST (lines starting with "- ") / @@FAQ ("Q:" and "A:" lines) / @@END
export const FORMAT_GUIDE=`Return plain text in exactly this format. Do not use JSON or code fences.
@@TITLE
<article H1, under 70 characters>
@@META_TITLE
<search title, under 60 characters, includes the primary keyword>
@@META_DESCRIPTION
<120 to 155 characters, states what the reader will be able to decide>
@@INTRO
<two or three sentences that answer the reader question directly>
@@SECTION <heading>
<one or more paragraphs; Markdown links like [anchor text](/products/example/) are allowed>
@@SECTION <heading>
<...repeat for every planned section...>
@@EXAMPLE
<optional: one short illustrative drawing example, labelled as illustrative; never a customer case>
@@CHECKLIST
- <item the reader can check on their drawing>
- <...>
@@FAQ
Q: <question>
A: <two to four sentence answer>
Q: <...>
A: <...>
@@END`;

const MARKER=/^@@\s*(TITLE|META_TITLE|META_DESCRIPTION|INTRO|SECTION|EXAMPLE|CHECKLIST|FAQ|END)\b[ \t]*(.*)$/i;
const clean=s=>s.replace(/\r/g,'').replace(/[ \t]+\n/g,'\n').replace(/\n{3,}/g,'\n\n').trim();

export function parseStudioText(raw){
 const text=String(raw||'').replace(/^```[a-z]*\n?|\n?```\s*$/gi,''),lines=text.split(/\r?\n/),doc={title:'',metaTitle:'',metaDescription:'',intro:'',sections:[],example:'',checklist:[],faq:[],ended:false};
 let current=null,buffer=[];
 const flush=()=>{if(!current)return;const body=clean(buffer.join('\n'));
  if(current.kind==='SECTION'){if(current.heading||body)doc.sections.push([current.heading.replace(/^#+\s*/,'').trim(),body]);}
  else if(current.kind==='CHECKLIST')doc.checklist=body.split('\n').map(l=>l.replace(/^\s*(?:[-*•]|\d+[.)])\s*/,'').trim()).filter(Boolean);
  else if(current.kind==='FAQ'){let q=null;for(const line of body.split('\n')){const m=line.match(/^\s*(Q|A)\s*[:：]\s*(.*)$/i);if(m&&m[1].toUpperCase()==='Q'){q={question:m[2].trim(),answer:''};doc.faq.push(q);}else if(m&&q)q.answer=(q.answer+' '+m[2]).trim();else if(q&&line.trim())q.answer=(q.answer+' '+line.trim()).trim();}doc.faq=doc.faq.filter(x=>x.question&&x.answer);}
  else{const key={TITLE:'title',META_TITLE:'metaTitle',META_DESCRIPTION:'metaDescription',INTRO:'intro',EXAMPLE:'example'}[current.kind];doc[key]=key==='intro'||key==='example'?body:body.replace(/\s+/g,' ');}
  current=null;buffer=[];};
 for(const line of lines){const m=line.match(MARKER);if(m){flush();const kind=m[1].toUpperCase();if(kind==='END'){doc.ended=true;break;}current={kind,heading:m[2]||''};continue;}if(current)buffer.push(line);}
 flush();
 // A heading written on the first body line instead of the marker line.
 doc.sections=doc.sections.map(([h,b])=>{if(h)return [h,b];const [first,...rest]=b.split('\n');return [first.replace(/^#+\s*/,'').trim(),clean(rest.join('\n'))];}).filter(([h,b])=>h&&b);
 return doc;
}
export function formatStudioText(doc){
 return ['@@TITLE',doc.title,'@@META_TITLE',doc.metaTitle,'@@META_DESCRIPTION',doc.metaDescription,'@@INTRO',doc.intro,...doc.sections.flatMap(([h,b])=>['@@SECTION '+h,b]),...(doc.example?['@@EXAMPLE',doc.example]:[]),'@@CHECKLIST',...doc.checklist.map(x=>'- '+x),'@@FAQ',...doc.faq.flatMap(x=>['Q: '+x.question,'A: '+x.answer]),'@@END'].join('\n');
}
// Structural problems that make a draft unusable (as opposed to quality issues found by the checks).
export function structureProblems(doc){
 const p=[];if(!doc.title)p.push('缺少标题');if(!doc.intro)p.push('缺少引言');if(doc.sections.length<3)p.push('章节少于3个');if(!doc.ended)p.push('输出没有以@@END结束，可能被截断');return p;
}
const STOP=new Set('a an the and or of for to in on with without is are be your you how what which when why does do vs versus guide'.split(' '));
export function slugify(title){return String(title).toLowerCase().replace(/[’'"]/g,'').split(/[^a-z0-9]+/).filter(w=>w&&!STOP.has(w)).slice(0,8).join('-').slice(0,80).replace(/-+$/,'')||'article';}
export const plainText=doc=>[doc.title,doc.intro,...doc.sections.flat(),doc.example,...doc.checklist,...doc.faq.flatMap(x=>[x.question,x.answer])].filter(Boolean).join('\n\n');
export function wordCount(doc){return (plainText(doc).replace(/\]\([^)]*\)/g,']').match(/[A-Za-z0-9][A-Za-z0-9'’-]*/g)||[]).length;}

// Build the site article object. FAQ answers become the closing section; FAQ schema is generated by the site.
export function toArticle(doc,{slug,category,product,processes=[],keywords=[],relatedLinks=[],readMinutes}){
 const sections=[...doc.sections];if(doc.faq.length)sections.push(['Frequently asked questions',doc.faq.map(x=>'**'+x.question+'**\n\n'+x.answer).join('\n\n')]);
 return {slug,title:doc.title,metaTitle:doc.metaTitle||doc.title,description:doc.metaDescription,category,product,cover:product,processes,intro:doc.intro,sections,checklist:doc.checklist,example:doc.example||'',keywords:keywords.slice(0,12),relatedLinks:relatedLinks.slice(0,8),sources:[],bodyFormat:'markdown',time:(readMinutes||Math.max(2,Math.round(wordCount(doc)/230)))+' MIN READ'};
}
