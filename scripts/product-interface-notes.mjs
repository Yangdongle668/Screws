export function productInterfaceTranslations(locale) {
  const index = languages.indexOf(locale);
  const rfq = ['Prepare the RFQ','准备询价资料','Anfrage vorbereiten','Preparar la solicitud','Preparare la richiesta','Préparer la demande de prix'];
  const copy = {[headings[0]]: headings[index], [rfq[0]]: rfq[index]};
  for (const note of Object.values(productInterfaceNotes)) {
    const source = note.copy[0].split(' → ');
    const translated = note.copy[index].split(' → ');
    source.forEach((line, i) => { copy[line] = translated[i]; });
  }
  return copy;
}

